/* =========================================
   ГЛАВНЫЙ ЭКРАН
   ========================================= */

function showHome() {

  homeScreen.classList.remove("hidden");

  contentScreen.classList.add("hidden");

  window.scrollTo({
    top: 0,
    behavior: "instant"
  });

}


/* =========================================
   ЭКРАН РАЗДЕЛА
   ========================================= */

function openSection(sectionId) {

  const section =
    content[sectionId];

  if (!section) {
    return;
  }


  const topicsHtml =
    section.topics
      .map((topic) => {

        return `

          <button
            class="topic-card"
            onclick="openArticle('${topic.id}')"
          >

            <b>
              ${topic.title}
            </b>

            <small>
              ${topic.description}
            </small>

            <span class="topic-arrow">
              ›
            </span>

          </button>

        `;

      })
      .join("");


  screenContent.innerHTML = `

    <div class="screen-inner">

      <button
        class="back-button"
        onclick="showHome()"
      >
        ← назад
      </button>


      <div class="section-heading">

        <h2>
          ${section.title}
        </h2>

        <p>
          ${section.description}
        </p>

      </div>


      <div class="topic-list">

        ${topicsHtml}

      </div>

    </div>

  `;


  homeScreen.classList.add("hidden");

  contentScreen.classList.remove("hidden");


  window.scrollTo({
    top: 0,
    behavior: "instant"
  });

}


/* =========================================
   СТАТЬИ
   ========================================= */

let currentArticle = null;

let currentPage = 0;

let previousScreen =
  "section";


function openArticle(articleId) {

  const article =
    articles[articleId];

  if (!article) {

    console.error(
      "статья не найдена:",
      articleId
    );

    return;
  }


  currentArticle = article;

  currentPage = 0;

  renderArticle();

}


/* =========================================
   РЕНДЕР СТРАНИЦЫ СТАТЬИ
   ========================================= */

function renderArticle() {

  if (!currentArticle) {
    return;
  }


  const page =
    currentArticle.pages[currentPage];


  const totalPages =
    currentArticle.pages.length;


  const hasPrevious =
    currentPage > 0;


  const hasNext =
    currentPage < totalPages - 1;


  screenContent.innerHTML = `

    <div class="article-screen">

      <button
        class="back-button"
        onclick="goBackFromArticle()"
      >
        ← назад
      </button>


      <h2 class="article-title">
        ${currentArticle.title}
      </h2>


      <div class="article-body">

        ${page}

      </div>


      <div class="article-navigation">

        ${
          hasPrevious
            ? `
              <button
                class="article-nav-button"
                onclick="previousPage()"
              >
                ← назад
              </button>
            `
            : `
              <div></div>
            `
        }


        ${
          hasNext
            ? `
              <button
                class="article-nav-button"
                onclick="nextPage()"
              >
                дальше →
              </button>
            `
            : ""
        }

      </div>


      <div class="article-page-number">

        ${currentPage + 1} / ${totalPages}

      </div>

    </div>

  `;


  window.scrollTo({
    top: 0,
    behavior: "instant"
  });

}


/* =========================================
   СТРАНИЦА ВПЕРЕД
   ========================================= */

function nextPage() {

  if (!currentArticle) {
    return;
  }


  if (
    currentPage <
    currentArticle.pages.length - 1
  ) {

    currentPage++;

    renderArticle();

  }

}


/* =========================================
   СТРАНИЦА НАЗАД
   ========================================= */

function previousPage() {

  if (!currentArticle) {
    return;
  }


  if (currentPage > 0) {

    currentPage--;

    renderArticle();

  }

}


/* =========================================
   НАЗАД ИЗ СТАТЬИ
   ========================================= */

function goBackFromArticle() {

  currentArticle = null;

  currentPage = 0;

  showSectionForArticle();

}


/* =========================================
   ВОЗВРАТ В РАЗДЕЛ
   ========================================= */

function showSectionForArticle() {

  /*
    определяем раздел по id текущей статьи
  */

  const articleTitle =
    currentArticle?.title;


  for (
    const sectionId in content
  ) {

    const section =
      content[sectionId];


    const found =
      section.topics.some(
        (topic) =>
          topic.title === articleTitle
      );


    if (found) {

      openSection(sectionId);

      return;

    }

  }


  showHome();

}


