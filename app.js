let currentSectionId = null;

let currentArticleId = null;

let currentPage = 0;


/* ==================================================
   DOM
================================================== */

const homeScreen = document.getElementById("homeScreen");

const contentScreen = document.getElementById("contentScreen");

const contentContainer =
  document.getElementById("contentContainer");

const quoteElement =
  document.getElementById("quote");

const newQuoteButton =
  document.getElementById("newQuote");


/* ==================================================
   ФРАЗА
================================================== */

function showNextQuote() {

  currentQuote++;

  if (currentQuote >= quotes.length) {
    currentQuote = 0;
  }

  quoteElement.style.opacity = "0";

  setTimeout(() => {

    quoteElement.textContent = quotes[currentQuote];

    quoteElement.style.opacity = "1";

  }, 120);

}


/* ==================================================
   ПОКАЗАТЬ ГЛАВНУЮ
================================================== */

function showHome() {

  currentSectionId = null;

  currentArticleId = null;

  currentPage = 0;

  contentScreen.classList.add("hidden");

  homeScreen.classList.remove("hidden");

  window.scrollTo(0, 0);
}


/* ==================================================
   ОТКРЫТЬ РАЗДЕЛ
================================================== */

function openSection(sectionId) {

  const section = sections[sectionId];

  if (!section) {
    return;
  }

  currentSectionId = sectionId;

  currentArticleId = null;

  currentPage = 0;

  contentScreen.classList.remove("hidden");

  homeScreen.classList.add("hidden");


  contentContainer.innerHTML = `

    <div class="screen-inner fade-in">

      <button
        class="back-button"
        id="sectionBackButton"
      >
        ← назад
      </button>


      <header class="section-header">

        <p class="section-kicker">
          ${section.kicker}
        </p>

        <h1>
          ${section.title}
        </h1>

        <p>
          ${section.description}
        </p>

      </header>


      <div class="topic-list">

        ${section.topics.map(topic => `

          <button
            class="topic-card"
            data-article="${topic.id}"
          >

            <div class="topic-card-content">

              <p class="topic-card-title">
                ${topic.title}
              </p>

              <p class="topic-card-description">
                ${topic.description}
              </p>

            </div>

            <span class="topic-arrow">
              ›
            </span>

          </button>

        `).join("")}

      </div>

    </div>

  `;


  document
    .getElementById("sectionBackButton")
    .addEventListener("click", showHome);


  document
    .querySelectorAll("[data-article]")
    .forEach(button => {

      button.addEventListener("click", () => {

        const articleId =
          button.dataset.article;

        openArticle(articleId);

      });

    });


  window.scrollTo(0, 0);
}


/* ==================================================
   ОТКРЫТЬ СТАТЬЮ
================================================== */

function openArticle(articleId) {

  const article = articles[articleId];

  if (!article) {
    return;
  }

  currentArticleId = articleId;

  currentPage = 0;

  currentSectionId = article.section;

  renderArticle();

}


/* ==================================================
   РЕНДЕР СТРАНИЦЫ СТАТЬИ
================================================== */

function renderArticle() {

  const article =
    articles[currentArticleId];

  if (!article) {
    return;
  }

  const page =
    article.pages[currentPage];

  const totalPages =
    article.pages.length;

  const isFirstPage =
    currentPage === 0;

  const isLastPage =
    currentPage === totalPages - 1;


  contentContainer.innerHTML = `

    <div class="screen-inner article-screen fade-in">

      <button
        class="back-button"
        id="articleBackButton"
      >
        ← назад
      </button>


      <header class="article-header">

        <p class="article-category">
          ${article.category}
        </p>

        <h1 class="article-title">
          ${article.title}
        </h1>

      </header>


      <article class="article-content">

        <h2>
          ${page.heading}
        </h2>

        ${page.content}

      </article>


      <div class="article-navigation">

        <button
          class="article-nav-button ${isFirstPage ? "disabled" : ""}"
          id="previousButton"
        >
          ← назад
        </button>


        <button
          class="article-nav-button next ${isLastPage ? "disabled" : ""}"
          id="nextButton"
        >
          дальше →
        </button>

      </div>


      <p class="page-counter">
        ${currentPage + 1} / ${totalPages}
      </p>

    </div>

  `;


  document
    .getElementById("articleBackButton")
    .addEventListener(
      "click",
      goBackFromArticle
    );


  document
    .getElementById("previousButton")
    .addEventListener(
      "click",
      previousPage
    );


  document
    .getElementById("nextButton")
    .addEventListener(
      "click",
      nextPage
    );


  window.scrollTo(0, 0);
}


/* ==================================================
   НАЗАД ИЗ СТАТЬИ
================================================== */

function goBackFromArticle() {

  if (currentSectionId) {

    openSection(currentSectionId);

    return;
  }

  showHome();
}


/* ==================================================
   СЛЕДУЮЩАЯ СТРАНИЦА
================================================== */

function nextPage() {

  const article =
    articles[currentArticleId];

  if (!article) {
    return;
  }

  if (
    currentPage <
    article.pages.length - 1
  ) {

    currentPage++;

    renderArticle();

  }
}


/* ==================================================
   ПРЕДЫДУЩАЯ СТРАНИЦА
================================================== */

function previousPage() {

  if (currentPage > 0) {

    currentPage--;

    renderArticle();

  }
}


