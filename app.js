/*- данные множественных чисел -*/
function pluralize(number, one, few, many) {
  const n = Math.abs(number) % 100;

  if (n >= 11 && n <= 19) return many;

  const last = n % 10;

  if (last === 1) return one;
  if (last >= 2 && last <= 4) return few;

  return many;
}

